#!/usr/bin/env python3
"""Bundle the compiled TypeScript codec for the playground and extension.

Compile first: tsc -p typescript
Then: python3 tools/build-web.py [--check]
No separate encoding implementation or bundler dependency.
"""
from pathlib import Path
import hashlib
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
assert sys.argv[1:] in ([], ["--check"]), "usage: build-web.py [--check]"
parts = []
for name in ("alphabet", "sigilcode"):
    text = (ROOT / "typescript" / "dist" / f"{name}.js").read_text()
    if name == "sigilcode":
        line = 'import { ALPHABET, IGNORED, UPPERCASE } from "./alphabet.js";\n'
        assert text.count(line) == 1, "compiled codec's import changed"
        text = text.replace(line, "")
    text = re.sub(r"^export ", "", text, flags=re.M)
    assert not re.search(r"^(import|export)\b", text, re.M), "unexpected module dependency"
    parts.append(text)
codec = ("// Generated by tools/build-web.py from typescript/{alphabet,sigilcode}.ts.\n"
         "(() => {\n'use strict';\n" + "\n".join(parts) +
         "\nglobalThis.SigilCode = Object.freeze({encode, decode, decodeReadings, layout, DecodeError});\n})();\n")
content = (codec + "\n" + (ROOT / "web" / "page.js").read_text() +
           "\nglobalThis.SigilPage.toggle(document.body);\n")
outputs = {ROOT / "web" / "sigilcode.js": codec,
           ROOT / "web" / "extension" / "content.js": content}
outputs[ROOT / "web" / "extension" / "fonts.css"] = (ROOT / "web" / "fonts.css").read_text()
outputs = {path: text.encode("utf-8") for path, text in outputs.items()}
# Reuse the alphabet generator's BLAKE3 to verify bundled third-party assets.
sys.path.insert(0, str(ROOT / "alphabet"))
from alphabet import blake3
font_root = ROOT / "web" / "fonts"
manifest = json.loads((font_root / "manifest.json").read_text())
assert manifest["version"] == 1
for asset in manifest["files"]:
    data = (font_root / asset["file"]).read_bytes()
    assert hashlib.sha256(data).hexdigest() == asset["sha256"], asset["file"]
    assert blake3(data).hex() == asset["blake3"], asset["file"]
    outputs[ROOT / "web" / "extension" / "fonts" / asset["file"]] = data
outputs[ROOT / "web" / "extension" / "fonts" / "manifest.json"] = (font_root / "manifest.json").read_bytes()
for name in ("LICENSE-MIT", "LICENSE-APACHE", "LICENSE-TGPPL", "LICENSE-BOSL.txt"):
    outputs[ROOT / "web" / "extension" / name] = (ROOT / name).read_bytes()
for path, data in outputs.items():
    if sys.argv[1:]:
        assert path.read_bytes() == data, f"stale generated file: {path}"
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
print("Browser bundles " + ("checked" if sys.argv[1:] else "written"))
