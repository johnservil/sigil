#!/usr/bin/env python3
"""Bundle the compiled TypeScript codec for the playground and extension, and
write the font and selection test pages from alphabet.txt and the reference.

Compile first: tsc -p typescript
Then: python3 tools/build-web.py [--check]
No separate encoding implementation or bundler dependency.
"""
from pathlib import Path
import hashlib
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
assert sys.argv[1:] in ([], ["--check"]), "usage: build-web.py [--check]"
parts = []
for name in ("alphabet", "sigilcode"):
    text = (ROOT / "typescript" / "dist" / f"{name}.js").read_text()
    if name == "sigilcode":
        line = 'import { ALPHABET, SKIPPED } from "./alphabet.js";\n'
        assert text.count(line) == 1, "compiled codec's import changed"
        text = text.replace(line, "")
    text = re.sub(r"^export ", "", text, flags=re.M)
    assert not re.search(r"^(import|export)\b", text, re.M), "unexpected module dependency"
    parts.append(text)
codec = ("// Generated by tools/build-web.py from typescript/{alphabet,sigilcode}.ts.\n"
         "(() => {\n'use strict';\n" + "\n".join(parts) +
         "\nglobalThis.SigilCode = Object.freeze({encode, decode, decodeReadings, layout, DecodeError, MARK});\n})();\n")
content = (codec + "\n" + (ROOT / "web" / "page.js").read_text() +
           "\nglobalThis.SigilPage.toggle(document.body);\n")
outputs = {ROOT / "web" / "sigilcode.js": codec,
           ROOT / "web" / "extension" / "content.js": content}
outputs[ROOT / "web" / "extension" / "fonts.css"] = (ROOT / "web" / "fonts.css").read_text()
outputs = {path: text.encode("utf-8") for path, text in outputs.items()}
# Reuse the alphabet generator's BLAKE3 to verify bundled third-party assets.
sys.path.insert(0, str(ROOT / "alphabet"))
from alphabet import blake3
font_root = ROOT / "web" / "fonts"
manifest = json.loads((font_root / "manifest.json").read_text())
assert manifest["version"] == 1
for asset in manifest["files"]:
    data = (font_root / asset["file"]).read_bytes()
    assert hashlib.sha256(data).hexdigest() == asset["sha256"], asset["file"]
    assert blake3(data).hex() == asset["blake3"], asset["file"]
    outputs[ROOT / "web" / "extension" / "fonts" / asset["file"]] = data
outputs[ROOT / "web" / "extension" / "fonts" / "manifest.json"] = (font_root / "manifest.json").read_bytes()
# The font and selection test pages, from alphabet.txt and the reference.
sys.path.insert(0, str(ROOT / "python"))
import base64
import sigilcode
letters = (ROOT / "alphabet.txt").read_text(encoding="utf-8")
page = (ROOT / "fonttest.html").read_text(encoding="utf-8")
page, k1 = re.subn(r'^(<p style="font-size:24px;word-break:break-all">).*$', lambda m: m.group(1) + letters, page, count=1, flags=re.M)
page, k2 = re.subn(r'^const ALPHABET = ".*";$', lambda m: f'const ALPHABET = "{letters}";', page, count=1, flags=re.M)
assert k1 == k2 == 1, "fonttest.html's alphabet lines"
outputs[ROOT / "fonttest.html"] = page.encode("utf-8")
values = [hashlib.sha256(b"Sigil copy test %d" % i).digest() for i in range(4)]
arabic, please = "\u0627\u0646\u0633\u062e \u0647\u0630\u0627", "\u0645\u0646 \u0641\u0636\u0644\u0643"
lines = [("hex", "ltr", "copy this", values[0].hex(), "please"),
         ("base64", "ltr", "copy this", base64.b64encode(values[0]).decode().rstrip("="), "please"),
         ("sigil", "ltr", "copy this", sigilcode.encode(values[0]), "please"),
         ("sigil, plain", "ltr", "copy this", sigilcode.encode(values[0], False), "please"),
         ("sigil after Arabic", "ltr", arabic, sigilcode.encode(values[1]), "please"),
         ("sigil in an Arabic paragraph", "rtl", arabic, sigilcode.encode(values[1]), please),
         ("sigil, plain, in an Arabic paragraph", "rtl", arabic, sigilcode.encode(values[1], False), please)]
lines += [(f"sigil ({i})", "ltr", "copy this", sigilcode.encode(values[i]), "please") for i in (2, 3)]
copy = ('<!doctype html><html lang="en" translate="no"><meta charset="utf-8"><title>Does a double-click select the whole sigil?</title>\n'
        '<!-- Generated by tools/build-web.py from the reference implementation; do not edit. -->\n'
        '<body style="font-size:20px;font-family:sans-serif;max-width:46em;margin:1em auto">\n'
        '<h3>Double-click (or long-press) the token in each line: does the whole token select?</h3>\n'
        '<p style="color:#666">Below the lines, this browser\'s own answer, by Selection.modify, which follows the same word boundaries. '
        'A sigil\'s first character is an invisible left-to-right mark, which keeps its handle\'s digits beside the rest when Arabic text comes before it: '
        'in each line the digits stay at the start of the sigil.</p>\n'
        + "".join(f'<p style="margin:1.2em 0" dir="{d}" data-name="{name}">{before} <span>{token}</span> {after}</p>\n'
                  for name, d, before, token, after in lines) +
        '<pre id="out"></pre><script>\n'
        "const out = [navigator.userAgent, ''];\n"
        "const visible = (t) => t.replace(/\\u200e/g, '').trim();\n"
        "for (const p of document.querySelectorAll('p[data-name]')) {\n"
        "  const t = p.querySelector('span').firstChild; const s = getSelection();\n"
        "  s.collapse(t, Math.floor(t.length / 2));\n"
        "  s.modify('move', 'backward', 'word'); s.modify('extend', 'forward', 'word');\n"
        "  const got = visible(s.toString());\n"
        "  out.push(p.dataset.name + ': ' + (got === visible(t.data) ? 'WHOLE' : 'part: ' + [...got].length + ' of ' + [...visible(t.data)].length));\n"
        "}\n"
        "document.getElementById('out').textContent = out.join('\\n');\n"
        "</script>\n")
outputs[ROOT / "copytest.html"] = copy.encode("utf-8")
for name in ("LICENSE-MIT", "LICENSE-APACHE", "LICENSE-TGPPL", "LICENSE-BOSL.txt"):
    outputs[ROOT / "web" / "extension" / name] = (ROOT / name).read_bytes()
for path, data in outputs.items():
    if sys.argv[1:]:
        assert path.read_bytes() == data, f"stale generated file: {path}"
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
print("Browser bundles " + ("checked" if sys.argv[1:] else "written"))
