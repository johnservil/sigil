"""The font test page (web/check.html), for tools/build-web.py: whether a
device's own fonts draw each candidate letter of alphabet/candidates.txt, the
result sent as a GitHub issue that tools/import-fonts.py records.

Its result block, the contract with alphabet/alphabet.py's font_result:

    <the browser's user agent>
    Sigil font test 0.2, page 2: <count> candidates, set <fingerprint>
    Drawn in full: <scripts> of <scripts> scripts

    <Script>: <drawn>/<count>[ missing <hex ranges>]
    ...

The fingerprint is the first 12 hex digits of the SHA-256 of candidates.txt's
letter lines. A change to how the page measures raises PAGE.
"""
import hashlib
