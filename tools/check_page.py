ROUND = "0.2"
# The page's measurement: page 2 draws each letter in a canvas a glyph cannot
# leave (page 1's 40 pixels clipped macOS's Canadian syllabics, whose cut
# halves then drew alike, Sam's result of November 4).
PAGE = 2


def candidates(text):
    """candidates.txt: {script: [code points]}, in the file's order."""
    out = {}
    for line in text.splitlines():
        if line and not line.startswith("#"):
            script, run = line.split()
            a, b = (int(x, 16) for x in run.split(".."))
            out.setdefault(script, []).extend(range(a, b + 1))
    return out


def fingerprint(text):
    """The candidate set's name: its letters' lines (candidates.txt without
    its comments), hashed."""
    letters = "".join(l + "\n" for l in text.splitlines() if l and not l.startswith("#"))
    return hashlib.sha256(letters.encode("utf-8")).hexdigest()[:12]


def tested_so_far(results):
    """The recorded results (alphabet.font_results()), for the page's list
    before the live one loads."""
    return [{"n": r["n"], "ua": r["ua"], "round": r["round"]} for r in results]


def wall(sigilcode, letters):
    """Handled sigils of 256-bit values that together use every letter: from
    a deterministic pool, the sigil with the most letters not yet used, until
    none is left unused (greedy, so a few more than the fewest)."""
    pool = []
    for i in range(6000):
        data = hashlib.sha256(b"Sigil font test %d" % i).digest()
        pool.append((data, sigilcode.encode(data)))
    unused, chosen = set(letters), []
    while unused:
        # Ties to the pool's order, so the handles look as random as the values.
        i = max(range(len(pool)), key=lambda i: (len(unused & set(pool[i][1])), -i))
        data, word = pool[i]
        assert unused & set(word), "the pool leaves letters unused"
        chosen.append((data.hex(), word))
        unused -= set(word)
    return chosen


